-- Người thực hiện lần đổi trạng thái gần nhất của món. Trigger lịch sử đọc các cột này,
-- nên service PHẢI đặt chúng mỗi lần đổi status (status_changed_by đã có từ V1).
ALTER TABLE order_item
    ADD COLUMN status_changed_by_type      VARCHAR(8),
    ADD COLUMN status_changed_by_device_id VARCHAR(64),
    ADD CONSTRAINT ck_order_item_changed_by_type CHECK (
        status_changed_by_type IS NULL OR status_changed_by_type IN ('GUEST', 'STAFF', 'SYSTEM')),
    ADD CONSTRAINT ck_order_item_changed_by_actor CHECK (
        (status_changed_by_type IS DISTINCT FROM 'GUEST' OR status_changed_by_device_id IS NOT NULL)
        AND (status_changed_by_type IS DISTINCT FROM 'STAFF' OR status_changed_by IS NOT NULL));
COMMENT ON COLUMN order_item.status_changed_by_type IS 'GUEST | STAFF | SYSTEM: ai đổi trạng thái gần nhất; service đặt cùng status_changed_by / status_changed_by_device_id.';

CREATE TABLE order_item_status_history (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_item_id       BIGINT      NOT NULL,
    from_status         VARCHAR(16),
    to_status           VARCHAR(16) NOT NULL,
    changed_by_type     VARCHAR(8)  NOT NULL,
    changed_by_user_id  BIGINT,
    device_id           VARCHAR(64),
    reason_code         VARCHAR(50),
    changed_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_order_item_status_history PRIMARY KEY (id),
    CONSTRAINT fk_oish_order_item FOREIGN KEY (order_item_id) REFERENCES order_item (id),
    CONSTRAINT fk_oish_changed_by FOREIGN KEY (changed_by_user_id) REFERENCES users (id),
    CONSTRAINT ck_oish_from_status CHECK (from_status IS NULL OR from_status IN (
        'PENDING', 'CONFIRMED', 'PREPARING', 'READY', 'SERVED', 'CANCELLED', 'REJECTED')),
    CONSTRAINT ck_oish_to_status CHECK (to_status IN (
        'PENDING', 'CONFIRMED', 'PREPARING', 'READY', 'SERVED', 'CANCELLED', 'REJECTED')),
    CONSTRAINT ck_oish_changed CHECK (from_status IS NULL OR from_status <> to_status),
    CONSTRAINT ck_oish_actor CHECK (
        (changed_by_type = 'STAFF' AND changed_by_user_id IS NOT NULL)
        OR (changed_by_type = 'GUEST' AND device_id IS NOT NULL)
        OR (changed_by_type = 'SYSTEM')),
    -- BR-O08: chuyển sang CANCELLED/REJECTED luôn có reasonCode.
    CONSTRAINT ck_oish_reason CHECK (to_status NOT IN ('CANCELLED', 'REJECTED') OR reason_code IS NOT NULL)
);
CREATE INDEX ix_oish_item ON order_item_status_history (order_item_id, changed_at);
-- Báo cáo thời gian từng công đoạn, tỷ lệ hủy/từ chối (FR-RPT-02).
CREATE INDEX ix_oish_report ON order_item_status_history (to_status, changed_at);
COMMENT ON TABLE order_item_status_history IS 'Lịch sử mọi lần chuyển trạng thái món: ai, khi nào, từ đâu sang đâu (BR-O09). Do trigger ghi tự động; chỉ thêm. Ứng dụng KHÔNG tự insert.';

-- Ghi lịch sử khi tạo món và mỗi lần đổi status.
--   INSERT: STAFF nếu created_by_user_id có giá trị, ngược lại GUEST (device_id người đặt).
--   UPDATE: theo status_changed_by_type; nếu NULL thì STAFF khi có status_changed_by, còn lại SYSTEM.
CREATE FUNCTION fn_order_item_status_history() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_type   VARCHAR;
    v_user   BIGINT;
    v_device VARCHAR;
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.status = OLD.status THEN
        RETURN NULL;
    END IF;
    IF TG_OP = 'INSERT' THEN
        v_user   := NEW.created_by_user_id;
        v_device := NEW.device_id;
        v_type   := CASE WHEN v_user IS NOT NULL THEN 'STAFF' ELSE 'GUEST' END;
    ELSE
        v_user   := NEW.status_changed_by;
        v_device := NEW.status_changed_by_device_id;
        v_type   := COALESCE(NEW.status_changed_by_type,
                             CASE WHEN v_user IS NOT NULL THEN 'STAFF' ELSE 'SYSTEM' END);
        IF v_type <> 'STAFF' THEN v_user := NULL; END IF;
    END IF;
    INSERT INTO order_item_status_history (
        order_item_id, from_status, to_status, changed_by_type, changed_by_user_id, device_id, reason_code, changed_at)
    VALUES (
        NEW.id,
        CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE OLD.status END,
        NEW.status, v_type, v_user, v_device,
        CASE WHEN NEW.status IN ('CANCELLED', 'REJECTED') THEN NEW.reason_code END,
        now());
    RETURN NULL;
END;
$$;
CREATE TRIGGER trg_order_item_status_history
    AFTER INSERT OR UPDATE OF status ON order_item
    FOR EACH ROW EXECUTE FUNCTION fn_order_item_status_history();

CREATE TRIGGER trg_order_item_status_history_append_only
    BEFORE UPDATE OR DELETE ON order_item_status_history
    FOR EACH ROW EXECUTE FUNCTION fn_append_only();

