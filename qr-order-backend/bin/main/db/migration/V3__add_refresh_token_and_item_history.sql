INSERT INTO order_item_status_history (order_item_id, from_status, to_status, changed_by_type, reason_code, changed_at)
SELECT id, NULL, status, 'SYSTEM',
       CASE WHEN status IN ('CANCELLED', 'REJECTED') THEN reason_code END,
       COALESCE(closed_at, served_at, ready_at, preparing_at, confirmed_at, created_at)
  FROM order_item;
