-- -----------------------------------------------------------------------------
-- 1. refresh_token (DB-01)
-- -----------------------------------------------------------------------------
CREATE TABLE refresh_token (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT      NOT NULL,
    family_id       UUID        NOT NULL,
    token_hash      CHAR(64)    NOT NULL,
    issued_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ NOT NULL,
    revoked_at      TIMESTAMPTZ,
    revoke_reason   VARCHAR(32),
    replaced_by_id  BIGINT,
    CONSTRAINT pk_refresh_token PRIMARY KEY (id),
    CONSTRAINT fk_refresh_token_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_refresh_token_hash UNIQUE (token_hash),
    -- Mỗi token chỉ được thay thế bởi đúng một token kế tiếp.
    CONSTRAINT uq_refresh_token_replaced_by UNIQUE (replaced_by_id),
    CONSTRAINT uq_refresh_token_id_family_user UNIQUE (id, family_id, user_id),
    -- Token kế tiếp phải cùng family và cùng user.
    CONSTRAINT fk_refresh_token_replaced_by FOREIGN KEY (replaced_by_id, family_id, user_id)
        REFERENCES refresh_token (id, family_id, user_id),
    -- SHA-256 hex của refresh token; không lưu token gốc (NFR-04).
    CONSTRAINT ck_refresh_token_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_refresh_token_expiry CHECK (expires_at > issued_at),
    CONSTRAINT ck_refresh_token_revoke_reason CHECK (revoke_reason IS NULL OR revoke_reason IN (
        'ROTATED', 'LOGOUT', 'REUSE_DETECTED', 'USER_LOCKED', 'USER_DISABLED',
        'ROLE_CHANGED', 'PERMISSION_CHANGED', 'PASSWORD_CHANGED', 'ADMIN_REVOKED')),
    CONSTRAINT ck_refresh_token_revoked CHECK (
        (revoked_at IS NULL) = (revoke_reason IS NULL)
        AND (revoked_at IS NULL OR revoked_at >= issued_at)),
    -- Có token kế tiếp thì lý do thu hồi phải là ROTATED. Chiều ngược lại (ROTATED thì phải có
    -- token kế tiếp) kiểm tra ở cuối transaction bởi trg_refresh_token_rotation_complete.
    CONSTRAINT ck_refresh_token_rotation CHECK (replaced_by_id IS NULL OR revoke_reason = 'ROTATED'),
    CONSTRAINT ck_refresh_token_replaced_self CHECK (replaced_by_id IS NULL OR replaced_by_id <> id)
);
-- Mỗi family tối đa 1 token chưa thu hồi (đầu chuỗi rotation).
CREATE UNIQUE INDEX ux_refresh_token_family_active ON refresh_token (family_id) WHERE revoked_at IS NULL;
-- Thu hồi toàn bộ token còn hiệu lực của user (BR-A04).
CREATE INDEX ix_refresh_token_user_active ON refresh_token (user_id) WHERE revoked_at IS NULL;
-- Scheduler dọn token hết hạn (§1 Scheduler).
CREATE INDEX ix_refresh_token_expires ON refresh_token (expires_at);
COMMENT ON TABLE refresh_token IS 'Refresh token xoay vòng (FR-AUTH-02). Rotation trong 1 transaction: (1) UPDATE token cũ SET revoked_at, revoke_reason=ROTATED WHERE revoked_at IS NULL (0 dòng = token đã bị dùng/thu hồi); (2) INSERT token mới cùng family; (3) UPDATE token cũ SET replaced_by_id = id mới. Dùng lại token đã thu hồi = REUSE_DETECTED, thu hồi cả family. Không phải dữ liệu nghiệp vụ: Scheduler được xóa theo cả family khi mọi token đã hết hạn.';
COMMENT ON COLUMN refresh_token.family_id IS 'Chuỗi rotation bắt đầu từ một lần đăng nhập.';

-- Thu hồi là một chiều; các cột định danh bất biến. Token đã thu hồi chỉ còn được sửa đúng một lần:
-- gắn replaced_by_id cho token ROTATED (bước 3 của rotation).
CREATE FUNCTION fn_refresh_token_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF (NEW.user_id, NEW.family_id, NEW.token_hash, NEW.issued_at, NEW.expires_at)
       IS DISTINCT FROM (OLD.user_id, OLD.family_id, OLD.token_hash, OLD.issued_at, OLD.expires_at) THEN
        RAISE EXCEPTION 'REFRESH_TOKEN_IMMUTABLE: chỉ được ghi thông tin thu hồi' USING ERRCODE = 'P0001';
    END IF;
    IF OLD.revoked_at IS NOT NULL AND NOT (
           OLD.revoke_reason = 'ROTATED' AND OLD.replaced_by_id IS NULL AND NEW.replaced_by_id IS NOT NULL
           AND (NEW.revoked_at, NEW.revoke_reason) IS NOT DISTINCT FROM (OLD.revoked_at, OLD.revoke_reason)) THEN
        RAISE EXCEPTION 'REFRESH_TOKEN_ALREADY_REVOKED: token % đã thu hồi', OLD.id USING ERRCODE = 'P0001';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_refresh_token_guard
    BEFORE UPDATE ON refresh_token
    FOR EACH ROW EXECUTE FUNCTION fn_refresh_token_guard();

-- Cuối transaction: token ROTATED phải có token kế tiếp (rotation không bỏ dở giữa chừng).
CREATE FUNCTION fn_refresh_token_rotation_complete() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM refresh_token
                WHERE id = NEW.id AND revoke_reason = 'ROTATED' AND replaced_by_id IS NULL) THEN
        RAISE EXCEPTION 'REFRESH_TOKEN_ROTATION_INCOMPLETE: token % ROTATED nhưng chưa có token kế tiếp', NEW.id
            USING ERRCODE = 'P0001';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER trg_refresh_token_rotation_complete
    AFTER INSERT OR UPDATE ON refresh_token
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_refresh_token_rotation_complete();

-- BR-A04: khóa/ngừng dùng tài khoản hoặc đổi role có hiệu lực ngay -> thu hồi mọi refresh token
-- còn hiệu lực trong cùng transaction. (Đổi permission: ứng dụng thu hồi với PERMISSION_CHANGED.)
CREATE FUNCTION fn_users_revoke_refresh_tokens() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_reason VARCHAR;
BEGIN
    IF NEW.status = 'LOCKED' AND OLD.status <> 'LOCKED' THEN
        v_reason := 'USER_LOCKED';
    ELSIF NEW.status = 'DISABLED' AND OLD.status <> 'DISABLED' THEN
        v_reason := 'USER_DISABLED';
    ELSIF NEW.role <> OLD.role THEN
        v_reason := 'ROLE_CHANGED';
    ELSE
        RETURN NULL;
    END IF;
    UPDATE refresh_token SET revoked_at = now(), revoke_reason = v_reason
     WHERE user_id = NEW.id AND revoked_at IS NULL;
    RETURN NULL;
END;
$$;
CREATE TRIGGER trg_users_revoke_refresh_tokens
    AFTER UPDATE OF role, status ON users
    FOR EACH ROW EXECUTE FUNCTION fn_users_revoke_refresh_tokens();

